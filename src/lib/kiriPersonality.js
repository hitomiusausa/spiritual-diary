// 応答検証（警告ログ用。v1 では応答をブロックしない）
// ==============================
export function validateKiriResponse(text) {
  const t = String(text ?? '');
  const warnings = [];

  if (/です|ます|ましょう|ございます|ください/.test(t)) {
    warnings.push('敬語定型');
  }

  // 通常2文以内・語りモード(相槌で促されたとき)でも4〜5文が上限のため、6文以上を逸脱とみなす
  const sentenceCount = (t.match(/[。！？!?]/g) ?? []).length;
  if (sentenceCount >= 6) {
    warnings.push('6文以上');
  }

  if ((t.match(/🐰|🌙/g) ?? []).length > 1) {
    warnings.push('絵文字過多');
  }

  if (/[*＊].+[*＊]/.test(t)) {
    warnings.push('ト書き');
  }

  if (/頑張って|元気を出して|無理しないで|リフレッシュ|しましょう|はどうですか/.test(t)) {
    warnings.push('励まし・提案定型');
  }

  return warnings;
}
