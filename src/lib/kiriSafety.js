// 危機の言葉と字面が重なるだけの、よくある無害な言い回し（「わたしに対して」「推しにたくさん」など）。
// 判定の前に区切り文字へ置きかえる（消して前後をつなげると、新しい一致を作ってしまうため）。
const BENIGN_PATTERNS = [/しにたい(して|する|へん)/g, /しにたくさん/g];

export function normalizeForSafety(text) {
  return String(text ?? "")
    .normalize("NFKC")
    .replace(/\s+/g, "")
    .replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .toLowerCase();
}

export function detectCrisis(...texts) {
  const joined = BENIGN_PATTERNS.reduce(
    (text, pattern) => text.replace(pattern, "|"),
    texts.map(normalizeForSafety).join("\n"),
  );
  if (!joined) return false;
  return CRISIS_PATTERNS.some((pattern) => pattern.test(joined));
}

// 日記の入力（出来事・直感）を判定する。分析API と、同意前で送信しない画面側の両方がこれを使う。
// 判定の対象欄はここだけで決める（画面側に欄やキーワードを重複させない）。
export function entryNeedsSupport(entry) {
  if (!entry) return false;
  return detectCrisis(entry.event, entry.intuition);
}

