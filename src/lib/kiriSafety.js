// normalizeForSafety() を通した文字列（ひらがな化・空白除去済み）に当てる。
const CRISIS_PATTERNS = [
  /(死|し)に(たい|たく|てえ)/,
  /(消|き)え(たい|たく|てしまいたい|てなくなりたい)/,
  /いなくなりたい/,
  /(生|い)きて(いたく|たく)ない/,
  /(生|い)きたくない/,
  /(生|い)きる(意味|いみ)(が|も)?(ない|わからない)/,
  /(生|い)きてる(意味|いみ)(が|も)?(ない|わからない)/,
  /自殺|じさつ|自死|自傷/,
  /りすか|りすとかっと|手首を(切|き)/,
  /おーばーどーず|(薬|くすり)を(大量|たいりょう)に/,
  /首を(吊|つ)|首(吊|つ)り|くびつり/,
  /(死|し)んだ(ほう|方)が(まし|楽|らく)/,
  /(死|し)ぬしかない|(死|し)ぬつもり|(死|し)のうと(思|おも)/,
  /(死|し)んでしまいたい/,
  /(殺|ころ)したい|(殺|ころ)してやる/,
];

export function normalizeForSafety(text) {
  return String(text ?? "")
    .normalize("NFKC")
    .replace(/\s+/g, "")
    .replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .toLowerCase();
}

export function detectCrisis(...texts) {
  const joined = texts.map(normalizeForSafety).join("\n");
  if (!joined) return false;
  return CRISIS_PATTERNS.some((pattern) => pattern.test(joined));
}

